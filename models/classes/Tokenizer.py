class Tokenizer:
    """
    USAGE:
        vocab = Tokenizer("dataset/train.txt")
        train = vocab.encode_file("dataset/train.txt")
        test  = vocab.encode_file("dataset/test.txt", flat=True)
    """

    UNK, EOS = "<unk>", "<eos>"

    def __init__(self, path, req_word_freq=3, lowercase=False):
        self.req_word_freq = req_word_freq
        self.lowercase = lowercase

        # Count word instances
        counts = {}
        for line in self._read_lines(path):
            for word in line:
                counts[word] = counts.get(word, 0) + 1

        # Create sorted array of unique words (including <unk>, <eos>)
        # Words that did not occur req_word_freq times will not be included
        self.itos = [self.UNK, self.EOS] + sorted(
            word
            for word, count in counts.items()
            if count >= req_word_freq and word not in (self.UNK, self.EOS)
        )

        # Dict for unique words to a number
        self.stoi = {word: idx for idx, word in enumerate(self.itos)}

    # ----------------------------------------------------------------------------
    # Additional class attributes
    # ----------------------------------------------------------------------------
    def __len__(self):
        return len(self.itos)

    @property
    def unk_id(self):
        return self.stoi[self.UNK]

    @property
    def eos_id(self):
        return self.stoi[self.EOS]

    # ----------------------------------------------------------------------------
    # TEXT PROCESSING
    # ----------------------------------------------------------------------------
    def _clean(self, line):
        """Parse @-@ style markers, lowercase if requested, split into tokens."""
        for mark in ("-", ",", "."):
            line = line.replace(f" @{mark}@ ", mark)

        if self.lowercase:
            line = line.lower()

        return line.split()

    def _read_lines(self, path):
        """Read file and split into array of tokens."""
        out = []
        with open(path, encoding="utf-8") as file:
            for line in file:
                line = line.strip()

                # Skip blank lines and headers
                if not line or (line.startswith("=") and line.endswith("=")):
                    continue

                out.append(self._clean(line) + [self.EOS])

        return out

    # ----------------------------------------------------------------------------
    # ENCODING/DECODING
    # ----------------------------------------------------------------------------
    def encode(self, str, flat=True):
        """
        Flat list of ids from word for FFN and RNN, one per paragraph for
        n-gram model
        """
        lines = [[self.stoi.get(w, self.unk_id) for w in str.strip().split()]]

        return [i for line in lines for i in line] if flat else lines

    def encode_file(self, path, flat=True):
        lines = [
            [self.stoi.get(w, self.unk_id) for w in line]
            for line in self._read_lines(path)
        ]

        return [i for line in lines for i in line] if flat else lines

    def decode(self, ids):
        """Convert integer generated by models to words"""
        return " ".join(self.itos[i] for i in ids)
